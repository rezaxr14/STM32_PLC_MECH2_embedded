/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_ADC1_Init();
  /* USER CODE BEGIN 2 */
  Lcd_PortType dataPorts[] = {GPIOB, GPIOB, GPIOB, GPIOB};
	Lcd_PinType dataPins[] = {GPIO_PIN_0, GPIO_PIN_1, GPIO_PIN_2, GPIO_PIN_3};
	lcd = Lcd_create(dataPorts, dataPins, GPIOB, GPIO_PIN_4, GPIOB, GPIO_PIN_5, LCD_4_BIT_MODE);

	Lcd_cursor(&lcd, 0, 0);
	Lcd_string(&lcd, "ADC Circular DMA");
	HAL_Delay(1000);
	Lcd_clear(&lcd);

	// Start DMA ONCE. Because it's circular + continuous, you NEVER have to call this again.
	HAL_ADC_Start_DMA(&hadc1, (uint32_t*)adc_values, ADC_SAMPLE_COUNT);
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
		if (data_ready_flag == 1)
    {
        // 1) Clear flag immediately
        data_ready_flag = 0;

        // 2) Sum up the 50 samples (the hardware is already collecting the next batch!)
        adc_sum = 0;
        for (int i = 0; i < ADC_SAMPLE_COUNT; i++)
        {
            adc_sum += adc_values[i];
        }
        adc_avg = adc_sum / ADC_SAMPLE_COUNT;
        
        // 3) Integer voltage math
        uint32_t volt_scaled = (adc_avg * 330) / 4095;
        uint8_t whole_part = volt_scaled / 100;
        uint8_t frac_part = volt_scaled % 100;
        
        // 4) Display data
        snprintf(lcd_buffer, sizeof(lcd_buffer), "Raw Avg: %d    ", adc_avg);
        Lcd_cursor(&lcd, 0, 0);
        Lcd_string(&lcd, lcd_buffer);
        
        snprintf(lcd_buffer, sizeof(lcd_buffer), "Volt: %d.%02d V   ", whole_part, frac_part);
        Lcd_cursor(&lcd, 1, 0);
        Lcd_string(&lcd, lcd_buffer);
        
        // 5) Delay just to give the screen breathing room (keeps UI readable)
        HAL_Delay(500); 
    }
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

