// UART RX Interrupt Callback to parse MATLAB commands
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance == USART1)
    {
        // 1. Extract the top 4 bits of the first byte to find the Command
        uint8_t command = (rx_buffer[0] >> 4) & 0x0F;
        
        // 2. Reconstruct the 12-bit data by combining the leftover 4 bits and the 8-bit Low Byte
        uint16_t value = ((rx_buffer[0] & 0x0F) << 8) | rx_buffer[1];
        
        // 3. Apply the data
        if (command == 1) // 1 = Frequency
        {
            target_freq = value;
        }
        else if (command == 2) // 2 = Duty Cycle
        {
            target_duty = value;
        }
        
        // Re-arm UART to wait for the next 2 bytes
        HAL_UART_Receive_IT(&huart1, rx_buffer, 2);
    }
}

